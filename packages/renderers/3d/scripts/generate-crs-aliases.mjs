import assert from 'node:assert/strict'
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { resolve } from 'node:path'

const args = process.argv.slice(2)
const sql = await readFile(args[0])
const license = await readFile(args[1])
const sha = bytes => createHash('sha256').update(bytes).digest('hex')
assert.equal(sha(sql), '752c139865b6b223449f68c46dc30449f43c26b0b958861294e3329c33f11a63')
assert.equal(sha(license), '6a8f30793e877d32e3f88b972f0970a051a3b5a26cd057d3993cb51e21c43319')
const rows = []
for (const line of sql.toString('utf8').split('\n')) {
  if (!line.startsWith('INSERT INTO "alias_name" VALUES(')) continue
  const values = [...line.matchAll(/'((?:[^']|'')*)'/g)].map(match => match[1].replaceAll("''", "'"))
  const [kind, authority, code, name] = values
  if (authority === 'EPSG' && ['projected_crs', 'geodetic_crs'].includes(kind)) rows.push([kind, code, name])
}
rows.sort((a, b) => {
  const left = JSON.stringify(a), right = JSON.stringify(b)
  return left < right ? -1 : left > right ? 1 : 0
})
assert.ok(rows.length > 1000)
const root = resolve(import.meta.dirname, '..')
// The original grant is copied byte-for-byte into licenses/. Trim only comment
// line padding so generated TypeScript also satisfies Git's whitespace checks.
const banner = '/*! PROJ 9.9.0 CRS aliases; upstream commit 1df2be61c0e4732aa1326126113776b291ae7657.\n' + license.toString('utf8').replace(/[ \t]+$/gm, '') + '\n*/\n'
await writeFile(resolve(root, 'src/geo3dCrsAliases.generated.ts'), banner +
  '// Generated by scripts/generate-crs-aliases.mjs from hash-verified upstream SQL.\n' +
  'export const crsAliases: ReadonlyArray<readonly [string, string, string]> = ' + JSON.stringify(rows) + '\n')
await mkdir(resolve(root, 'licenses'), {recursive: true})
await writeFile(resolve(root, 'licenses/PROJ-COPYING.txt'), license)
const preservedNotice = banner.slice(3, -3).trim() + '\n'
await writeFile(resolve(root, 'licenses/PROJ-NOTICE.txt'), preservedNotice)
const noticePath = resolve(root, 'GEO3D_THIRD_PARTY_NOTICES.md')
const start = '<!-- BEGIN PROJ ALIAS NOTICE -->'
const end = '<!-- END PROJ ALIAS NOTICE -->'
const section = `${start}\n\n## Retained PROJ alias-table grant\n\n${preservedNotice}\n${end}`
const priorNotice = await readFile(noticePath, 'utf8')
assert.equal(priorNotice.includes(start), priorNotice.includes(end), 'Incomplete generated PROJ notice section')
await writeFile(noticePath, priorNotice.includes(start)
  ? priorNotice.slice(0, priorNotice.indexOf(start)) + section + priorNotice.slice(priorNotice.indexOf(end) + end.length)
  : priorNotice.trimEnd() + '\n\n' + section + '\n')
console.log(`Generated ${rows.length} authority aliases from the reviewed PROJ snapshot.`)
